"""Compile invoices with Typst, replacing PDFs only after success."""

import os
import shutil
import subprocess
import tempfile
from pathlib import Path

from .config import Paths
from .errors import BillshitError


class Renderer:
    def __init__(self, paths: Paths):
        self.paths = paths

    def check(self, output: Path, force: bool):
        if shutil.which("typst") is None:
            raise BillshitError("Typst not found in PATH (tested with 0.15.1)")
        if output.exists() and not force and b"Typst" not in output.read_bytes():
            raise BillshitError(f"{output} was not generated by Typst. Add --force to overwrite it.")

    def _command(self, invoice: Path, output: Path):
        relative = invoice.relative_to(self.paths.root).as_posix()
        return ["typst", "compile", "--root", str(self.paths.root),
                "--font-path", str(self.paths.root / "sablona/fonts"), "--ignore-system-fonts",
                "--input", f"data={relative}", str(self.paths.root / "sablona/faktura.typ"), str(output)]

    def render(self, invoice: Path, output: Path, force=False):
        self.check(output, force)
        if not invoice.is_file():
            raise BillshitError(f"Missing {invoice} – generate the invoice from Toggl first")
        fd, name = tempfile.mkstemp(dir=output.parent, prefix=f".{output.stem}.", suffix=".pdf")
        os.close(fd)
        temporary = Path(name)
        try:
            self._run(self._command(invoice, temporary))
            os.replace(temporary, output)
        finally:
            temporary.unlink(missing_ok=True)
        print(f"Generated: {output}")

    @staticmethod
    def _run(command):
        try:
            subprocess.run(command, check=True)
        except subprocess.CalledProcessError as error:
            raise BillshitError(f"Typst failed (exit {error.returncode})") from error

