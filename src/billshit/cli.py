"""Argument parsing and terminal errors. No billing rules live here."""

import argparse
import re
import sys
from decimal import Decimal
from pathlib import Path

from .app import Options, run
from .config import Paths
from .errors import BillshitError
from .period import Period


def parse_period(value: str) -> Period:
    try:
        return Period.parse(value)
    except ValueError as error:
        raise argparse.ArgumentTypeError(f"invalid month {value!r}; expected MM-YYYY") from error


def parse_expenses(value: str) -> Decimal:
    if not re.fullmatch(r"-?[0-9]+(?:[.,][0-9]{1,2})?", value):
        raise argparse.ArgumentTypeError("expenses must be an amount, e.g. 1193.26")
    return Decimal(value.replace(",", "."))


def parser() -> argparse.ArgumentParser:
    result = argparse.ArgumentParser(
        prog="billshit", usage="%(prog)s [OPTIONS] [MM-YYYY]", allow_abbrev=False,
        description="Import hours from Toggl and generate a Czech PDF invoice. "
                    "Create a new invoice or update an existing one. Defaults to the current month.",
        epilog="Examples:\n  billshit 10-2026\n  billshit --expenses 1193.26 10-2026\n\n"
               "Output: data/faktury/MM-YYYY/ inside the project directory.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    result.add_argument("month", metavar="MM-YYYY", nargs="?", type=parse_period,
                        default=Period.current(), help="invoice month (default: current month)")
    result.add_argument("--expenses", type=parse_expenses, metavar="AMOUNT", help="reimbursable expenses in CZK")
    result.add_argument("-f", "--force", action="store_true", help="allow overwriting a PDF not generated by Typst")
    result.add_argument("--pdf", action="store_true", help="render the saved invoice without importing Toggl hours")
    return result


def main(argv=None, root: Path | None = None) -> int:
    args = parser().parse_args(argv)
    options = Options(period=args.month, expenses=args.expenses, pdf=args.pdf, force=args.force)
    paths = Paths.for_project(root or Path(__file__).resolve().parents[2])
    try:
        return run(options, paths)
    except (BillshitError, OSError) as error:
        print(f"billshit: {error}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print("\nInterrupted.", file=sys.stderr)
        return 130
